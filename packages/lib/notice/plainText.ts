/**
 * お知らせ本文（Markdown）から記号を除いた1続きの文章を作る（ポップアップの要約表示用）。
 * 見出し・箇条書き・強調・リンク・コード等の記号を外し、改行は空白にまとめる。
 */
export function toNoticePlainText(markdown: string): string {
  return markdown
    .replace(/```[\s\S]*?```/g, ' ')            // コードブロック
    .replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')       // 画像
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')     // リンクは文字だけ残す
    .replace(/^\s{0,3}#{1,6}\s+/gm, '')          // 見出し
    .replace(/^\s{0,3}>\s?/gm, '')               // 引用
    .replace(/^\s*(?:[-*+]|\d+\.)\s+/gm, '')     // 箇条書き
    .replace(/^\s*(?:[-*_]\s*){3,}$/gm, ' ')     // 区切り線
    .replace(/^\|?[\s:|-]+\|[\s:|-]*$/gm, ' ')   // 表の区切り行
    .replace(/\|/g, ' ')                         // 表の縦線
    .replace(/(\*\*|__|\*|~~|`)/g, '')           // 強調・打ち消し・インラインコード（単語中の _ は残す）
    .replace(/\s+/g, ' ')
    .trim();
}
