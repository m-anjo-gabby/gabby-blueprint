---------------------------------------------
-- 専属コーチのマッチングで申請・承認できる「予約できる回数」の下限の割合 (2026-10-09 追加)
---------------------------------------------
-- 【背景】
-- 毎週の枠（コマ）を申請したとき、契約期間内の回がコーチの他の予定（他の生徒の定期スケジュール・
-- 個別のセッション・休み）と重なる回は予約できない。予約できる回数がこの割合以上なら申請・承認でき、
-- 残りは生徒とコーチが個別に日時を調整する（未予約として表示）。割合の判定は
-- fn_matching_slot_availability() が行い、申請時（生徒）・承認時（コーチ・アドミン）・申請カレンダーの表示の
-- すべてがこの値を使う。アプリ側に同じ値を持たないため、割合を変えるときは本関数だけを作り直す。
--
-- 【分母】
-- 契約上の回数（コマの目標回数 target_sessions）と、申請時点から契約終了までに実施できる回数の少ない方。
-- 開始が遅れて期間が足りない分は、どの時間を選んでも変わらないため判定に含めない（未予約として表示のみ）。
-- 例: 12回のコマで 0.8 なら 10回以上（9.6 の切り上げ）、0.7 なら 9回以上（8.4 の切り上げ）。
--
-- STABLE にしているのは、作り直したときに実行計画へ埋め込まれた古い値が使われないようにするため。
---------------------------------------------
CREATE OR REPLACE FUNCTION public.matching_min_bookable_rate()
RETURNS numeric
LANGUAGE sql
STABLE
AS $$ SELECT 0.8::numeric $$;

COMMENT ON FUNCTION public.matching_min_bookable_rate() IS '専属コーチのマッチングで、契約期間内に予約できる回数の下限の割合（fn_matching_slot_availability が使う）';
